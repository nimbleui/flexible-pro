/**
 * 插槽（Slot）架构定义
 * 本文件定义了组件的插槽结构。
 * 插槽是组件内容分发机制的核心，允许父组件向子组件的指定位置注入内容，
 * 类似于 Vue 的 slot 机制或 Web Components 的 slot 元素。
 */

/**
 * 插槽在容器内的命中区域接口
 * 用容器矩形的比例（0–1）描述，而不是绝对像素。
 *
 * 选比例而非像素的原因：容器被缩放或拉伸时区域随之伸缩，header / footer 这类贴边
 * 区域才会一直贴在正确的边上；用像素声明会让「把容器拉宽」变成「中部插槽变小」。
 * 坐标原点取容器矩形左上角，与世界矩形同一轴。
 */
export interface SlotRegion {
  /** 区域左边界相对容器宽度的比例 @default 0 */
  x?: number
  /** 区域上边界相对容器高度的比例 @default 0 */
  y?: number
  /** 区域宽度相对容器宽度的比例 @default 1 */
  width?: number
  /** 区域高度相对容器高度的比例 @default 1 */
  height?: number
}

/**
 * 组件插槽定义接口
 * 声明组件中的一个内容分发点（插槽），其他组件可以向此插槽中填充内容。
 * 每个插槽可以指定允许接收的组件类型和最大子节点数量限制。
 */
export interface SlotDefinition {
  /** 插槽名称标识，如 "default"（默认插槽）、"header"（头部插槽）、"footer"（底部插槽） */
  name: string
  /** 插槽在编辑器中的显示标题 */
  title: string
  /** 插槽的描述说明（可选），说明该插槽的用途和预期内容 */
  description?: string
  /**
   * 该插槽允许接收的组件名称列表（可选）
   * 为空或 undefined 时表示允许任意组件。
   * 例如 ['Button', 'Input'] 表示只允许放入按钮和输入框。
   */
  accepts?: string[]
  /**
   * 该插槽最多可容纳的子节点数量（可选）
   * 不设置或为 0 时表示不限制。
   * 常用于限制只能放入一个子节点的插槽（如标签页的标题插槽）。
   */
  maxChildren?: number
  /**
   * 该插槽在容器内的命中区域（可选），供拖入判定「落到了哪一格」。
   *
   * 省略表示覆盖整个容器矩形；同一组件里出现多个全屏区域时，按声明顺序取先者，
   * 因此「先声明窄条、后声明全屏兜底插槽」是有意为之的写法。
   */
  region?: SlotRegion
}
