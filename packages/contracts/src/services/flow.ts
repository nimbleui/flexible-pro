import type { Disposable } from '@lc/kernel'
import type { FlowDefinition } from '@lc/schema'

/**
 * 流程图仓库服务（应用级）。
 *
 * 图是**可独立发版的文档**，不属于任何单个页面文档，所以它不能像 `PageSchema.connections`
 * 那样由 EditorRealm 的文档服务直接给出。本服务是运行时取图的唯一入口。
 *
 * 取图只有一个动作：按 id 取已发布版本。「哪个事件的哪一步该跑哪张图」这条绑定存在页面
 * 文档的 `connection.flowId` 上，由用户在设计器的事件面板里选定——绑定的所有权跟着使用者的
 * 心智走，而不是跟着数据存放处走。本服务因此不再按事件键反查，也不再需要「文档 + 节点 + 事件」
 * 三段键：一张图可以被任意多个事件引用，而一个事件只可能指向一张图，冲突面从结构上消失了。
 *
 * 只提供查询与变更订阅、不提供执行：执行归 `ActionService`，否则「谁触发什么」会有两个
 * 地方各自决定一次，调试时无法对照。
 *
 * 与 `toast` / `navigation` 同类，本服务名不在保留清单里：宿主换成服务端图仓库、或按租户
 * 做权限过滤，都是正当用法。没装本服务的运行环境里，页面事件只跑动作链，行为与引入流程图
 * 之前完全一致。
 */
export interface FlowService {
  /**
   * 按 id 取**已发布**的流程图。
   *
   * 只认已发布版本：草稿参与执行会让作者正在编辑的半张图抢先跑起来。
   * 图不存在与图是草稿都返回 `undefined`，调用方不必区分——两者都不该被执行，
   * 「绑定指向了不可用的图」这件事由校验与面板的状态标注负责说明。
   */
  getPublished(flowId: string): FlowDefinition | undefined

  /**
   * 当前项目的全部流程图，含草稿。
   *
   * 两个消费方都要它，而且都要「草稿也在内」这一半：
   *  - 页面事件的绑定下拉要把草稿列出来但标注清楚，绑上去不生效时用户才知道下一步该发布，
   *   而不是对着一个凭空消失的选项猜；
   *  - 校验要分得清「引用的图不存在」与「引用的图还是草稿」，两者都归成「不存在」就是在误导。
   *
   * 只要当前项目的：页面写下的 `flowId` 只是个字符串，跨项目粘一个进来照样存得下。
   * 子流程候选与绑定候选都由调用方按 `status === 'published'` 自己筛，本服务不再另出一份
   * 只含已发布的清单——两份列表迟早对不上，而差别只是省一次 filter。
   */
  list(): readonly FlowDefinition[]

  /**
   * 图仓库内容变化时的通知（发布、下线、改名、删除）。
   *
   * 绑定本身现在写在页面文档里，但「这张图还在不在、还是不是已发布、叫什么名字」仍然只在
   * 图那一侧。面板要显示所绑图当前的发布状态、下拉要列出刚发布的图，都需要这个信号；
   * 只订阅文档变更的界面会一直停留在旧状态，看起来像漏配。
   */
  onDidChange(listener: () => void): Disposable
}
